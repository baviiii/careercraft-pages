/* ───────────────────────────────────────────────────────────────
   Theme + layout map for vector PDF resume export.
   Every template_id resolves to one of four base layouts plus
   a typography/colour scheme.
   ─────────────────────────────────────────────────────────────── */

export type LayoutVariant = "classic" | "accent" | "sidebar" | "minimal";

export type FontFamily = "Helvetica" | "Times-Roman";

export type SkillsStyle = "chip" | "dotted" | "inline" | "bullet";

export type SectionHeaderStyle = "underline" | "bar" | "caps-tracked" | "rule";

export interface ResumeTheme {
  layout: LayoutVariant;
  font: FontFamily;
  /** Main accent (section heads, hairlines, name in some layouts). */
  accent: string;
  /** Secondary accent used by sidebar fills, chip fills, rules. */
  accentSoft: string;
  /** Default body ink. */
  ink: string;
  /** Muted secondary text. */
  mute: string;
  /** Hairline / divider colour. */
  hair: string;
  /** Page background (white in most). */
  bg: string;
  /** Sidebar background, when layout = "sidebar". */
  sidebarBg: string;
  /** Sidebar ink, when layout = "sidebar". */
  sidebarInk: string;
  /** Color of the name in the header. */
  headerName: string;
  sectionHeader: SectionHeaderStyle;
  skills: SkillsStyle;
  /** Uppercase the name in the header? */
  uppercaseName: boolean;
}

